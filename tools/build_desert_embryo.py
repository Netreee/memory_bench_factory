def write_json(path: Path, value) -> None:
    """以统一格式写入 JSON。"""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def signal_doc_id(doc_id: str) -> str:
    """把信号文档 ID 归一为前端和审计器共同识别的形式。"""
    if "_sig_" in doc_id:
        return doc_id
    head, sep, tail = doc_id.partition("_")
    return f"{head}_sig_{tail}" if sep else f"sig_{doc_id}"


def make_timeline(points: list[tuple[int, str | None]]) -> list[dict]:
    """把稀疏章节值编译为 WorldState 操作序列。"""
    out: list[dict] = []
    previous = None
    for session, value in points:
        if value is None:
            op = "EXPIRE"
        elif previous is None:
            op = "SET"
        else:
            op = "UPDATE"
        out.append({
            "session": session,
            "date": DATES[session],
            "op": op,
            "value": value,
            "prev": previous,
        })
        previous = value
    return out


def make_doc(
    doc_id: str,
    doc_type: str,
    title: str,
    content: str,
    *,
    reliability: str = "medium",
    claims: list[str] | None = None,
    conflict: bool = False,
    filler: bool = False,
) -> dict:
    """创建一篇带来源等级、事实引用与草堆标签的文档。"""
    doc = {
        "doc_id": doc_id if filler else signal_doc_id(doc_id),
        "type": doc_type,
        "title": title,
        "content": content.strip(),
        "reliability": reliability,
        "claim_refs": [] if filler else (claims or []),
        "fact_refs": [] if filler else (claims or []),
    }
    if conflict:
        doc["is_conflict"] = True
    if filler:
        doc["is_filler"] = True
    return doc


